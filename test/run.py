# ------------------------------------------------------------------- masking

def path_rx(root):
    """the directory as it may be printed: either slash, and what follows"""
    parts = [p for p in re.split(r"[\\/]", root) if p != ""]
    body = r"[\\/]".join(re.escape(p) for p in parts)
    return re.compile(body + r"[A-Za-z0-9_:.~+\\/-]*", re.I)


def build_masks():
    """Everything that would differ between two machines or two minutes."""
    subs = []
    # the directories this suite runs out of, as real paths rather than a
    # guessed-at name: the guess once matched every word holding a "w"
    # the shell inside the terminal panel prints its own spelling of the
    # temp directory, /tmp/<name>, which no Windows form of it matches
    subs.append((path_rx("/tmp/" + os.path.basename(BUILD)), "<PATH>"))
    # a path the view cut off before its end is still a path
    subs.append((re.compile(r"[A-Za-z]:[\\/][A-Za-z0-9_.~+\\/-]*[\\/]mme-test[A-Za-z0-9_.~+\\/-]*"), "<PATH>"))
    subs.append((re.compile(r"/tmp/[A-Za-z0-9_.~+/-]*"), "<PATH>"))
    for root in (BUILD, HERE, EDITOR):
        subs.append((path_rx(root), "<PATH>"))
        posix = "/" + root[0].lower() + root[2:].replace("\\", "/") if root[1:2] == ":" else root
        subs.append((path_rx(posix), "<PATH>"))
    # a path that the shell's prompt wrapped onto the next row keeps only its tail
    subs.append((re.compile(r"[A-Za-z0-9_.~+-]*[\\/](?:reg|fix|work|golden)[\\/][A-Za-z0-9_.\\/-]*"),
                 "<PATH>"))
    for var, tag in (("USERNAME", "<USER>"), ("COMPUTERNAME", "<HOST>"),
                     ("USERDOMAIN", "<DOMAIN>")):
        v = os.environ.get(var)
        if v:
            subs.append((re.compile(re.escape(v), re.I), tag))
    # "2 years ago" in git blame and the history list
    subs.append((re.compile(r"\b\d+ (?:second|minute|hour|day|week|month|year)s? ago"),
                 "<AGO>"))
    subs.append((re.compile(r"\b(?:just now|seconds ago)\b"), "<AGO>"))
    # the OUTPUT channel's timestamps and command timings
    subs.append((re.compile(r"\d{4}-\d\d-\d\d \d\d:\d\d:\d\d"), "<DATETIME>"))
    subs.append((re.compile(r"\[\d+(?:\.\d+)?m?s\]"), "[<MS>]"))
    subs.append((re.compile(r"\b\d\d:\d\d(?::\d\d)?\b"), "<TIME>"))
    # the shell's own version, which is not ours to pin
    subs.append((re.compile(r"mmc \d+\.\d+\.\d+"), "mmc <VER>"))
    return subs


MASKS = build_masks()


def normalise(text, extra):
    for rx, rep in MASKS + list(extra):
        text = rx.sub(rep, text)
    # trailing blanks never carry meaning and the terminal pads with them
    return "".join(line.rstrip() + "\n" for line in text.splitlines())


