def sync_tree():
    """tree/ is the editor's sources as they are right now. Copying them here
    every build means the suite can never be measuring a stale tree."""
    if not os.path.isfile(os.path.join(EDITOR, "mme.c")):
        raise SystemExit("cannot find the editor's sources at %s" % EDITOR)
    if not os.path.isdir(TREE):
        os.makedirs(TREE)
    n = 0
    for name in os.listdir(EDITOR):
        if not name.endswith((".c", ".h", ".rc", ".ico")) and name not in ("build.bat", "makefile"):
            continue
        src = os.path.join(EDITOR, name)
        if not os.path.isfile(src):
            continue
        dst = os.path.join(TREE, name)
        same = (os.path.isfile(dst) and os.path.getsize(dst) == os.path.getsize(src)
                and os.path.getmtime(dst) >= os.path.getmtime(src))
        if not same:
            shutil.copyfile(src, dst)
            n += 1
    print("tree/ synced from %s (%d file(s) changed)" % (EDITOR, n))


def build(tree, dest):
    env = dict(os.environ)
    env["MME_DEST"] = dest
    if not os.path.isdir(dest):
        os.makedirs(dest)
    r = subprocess.run(["cmd.exe", "/c", os.path.join(tree, "build.bat")],
                       env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    sys.stdout.write(r.stdout.decode("utf8", "replace"))
    if r.returncode:
        raise SystemExit("build of %s failed" % tree)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--update", action="store_true", help="re-bless the goldens")
    ap.add_argument("-k", "--filter", default="", help="only names containing this")
    ap.add_argument("--repeat", type=int, default=1, help="run the suite N times")
    ap.add_argument("--jobs", type=int, default=8, help="scenarios at once")
    ap.add_argument("--list", action="store_true", help="print the scenarios")
    ap.add_argument("--build", action="store_true", help="rebuild bin/ and pbin/")
    args = ap.parse_args()

    if args.list:
        for s in SCENARIOS:
            print("%-28s %-22s %s" % (s.name, s.target, s.guards))
        return 0

    if args.build:
        sync_tree()
        import mkprof
        mkprof.main()                       # ptree/ from the sources just synced
        build(TREE, os.path.join(HERE, "bin"))
        build(PTREE, os.path.join(HERE, "pbin"))

    for p in (HARNESS, BIN, PBIN):
        if not os.path.isfile(p):
            raise SystemExit("%s is missing: run  python run.py --build" % p)
    if not os.path.isdir(FIX):
        raise SystemExit("fix/ is missing: run  python mkfix.py")

    todo = [s for s in SCENARIOS if args.filter in s.name]
    if not todo:
        raise SystemExit("no scenario matches %r" % args.filter)

    if not args.filter and os.path.isdir(GOLDEN):
        want = set(s.name + ".txt" for s in SCENARIOS) | set(["perf-baseline.json"])
        stale = sorted(set(os.listdir(GOLDEN)) - want)
        if stale:
            print("stale goldens, from scenarios that are gone: %s" % ", ".join(stale))

    base = {}
    if os.path.isfile(PERF_BASELINE):
        base = json.load(io.open(PERF_BASELINE, encoding="utf-8"))

    bad = 0
    first = {}
    new_base = dict(base)
    for pass_no in range(args.repeat):
        t0 = time.time()
        results = {}
        # the screens can all be driven at once; the perf scenarios are timed,
        # so they get the machine to themselves, one after the other
        quick = [s for s in todo if not s.perf]
        timed = [s for s in todo if s.perf]
        # a mismatch is retried once, but only when there is a golden to
        # compare with and no --repeat asking about determinism
        retry = not args.update and args.repeat == 1
        with ThreadPoolExecutor(max_workers=args.jobs) as ex:
            futs = {ex.submit(run_one, s, False,
                              read_golden(s.name) if retry else None): s for s in quick}
            for f, s in futs.items():
                results[s.name] = f.result()
        for s in timed:
            results[s.name] = run_one(s, True)
        fails = []
        for s in todo:
            text, ticks, took = results[s.name]
            tag = "" if args.repeat == 1 else " [pass %d]" % (pass_no + 1)
            if args.repeat > 1:
                if pass_no == 0:
                    first[s.name] = text
                elif first[s.name] != text:
                    fails.append((s, "NOT DETERMINISTIC between passes",
                                  diff(s.name + " (pass 1)", first[s.name], text)))
                    continue
            if args.update:
                write_golden(s.name, text)
                if s.perf:
                    new_base[s.name] = ticks
                print("blessed  %-30s %5.1fs%s%s" % (
                    s.name, took, tag,
                    ("  max tick %d us, %d over %dms" % (ticks["max_us"], ticks["over_20ms"], TICK_MS)) if s.perf else ""))
                continue
            want = read_golden(s.name)
            if want is None:
                fails.append((s, "no golden: run --update", ""))
                continue
            if want != text:
                fails.append((s, "the screen differs from the golden",
                              diff(s.name, want, text)))
                continue
            if s.perf:
                ok, msg = perf_check(s.name, ticks, base)
                if not ok:
                    fails.append((s, "the event loop got slower: " + msg, ""))
                    continue
                print("ok       %-30s %5.1fs%s  %s" % (s.name, took, tag, msg))
            else:
                print("ok       %-30s %5.1fs%s" % (s.name, took, tag))
        for s, why, d in fails:
            print("")
            print("FAIL     %s" % s.name)
            print("         guards: %s" % s.guards)
            print("         %s" % why)
            if d:
                for line in d.splitlines():
                    print("    " + line)
        bad += len(fails)
        print("")
        if FLAKY:
            print("flaky: %s - differed once, matched on the retry. The guard holds,"
                  % ", ".join(sorted(set(FLAKY))))
            print("       but the screen is being read before mme has settled.")
            del FLAKY[:]
        print("%d scenario(s), %d failed, %.1fs%s" % (
            len(todo), len(fails), time.time() - t0,
            "" if args.repeat == 1 else " (pass %d of %d)" % (pass_no + 1, args.repeat)))

    if args.update:
        io.open(PERF_BASELINE, "w", encoding="utf-8", newline="\n").write(
            json.dumps(new_base, indent=2, sort_keys=True) + "\n")
        print("perf baseline written to golden/perf-baseline.json")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
