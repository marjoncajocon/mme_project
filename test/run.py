def diff(name, want, got):
    return "".join(difflib.unified_diff(
        want.splitlines(True), got.splitlines(True),
        fromfile="golden/%s.txt" % name, tofile="this run", n=2))


# a regression has to be caught, a slow machine has not: a scenario may take
# four times its baseline, but never less than this floor
PERF_FACTOR = 4.0
PERF_FLOOR_US = 150000
PERF_COUNT_FLOOR = 8


def perf_check(name, ticks, base):
    """-> (ok, message)"""
    b = base.get(name)
    if b is None:
        return True, "no baseline yet (--update records one)"
    lim_us = max(PERF_FACTOR * b["max_us"], PERF_FLOOR_US)
    lim_n = max(PERF_FACTOR * b["over_20ms"], PERF_COUNT_FLOOR)
    msg = ("max tick %d us (baseline %d, limit %d), ticks over %dms: %d "
           "(baseline %d, limit %d)" % (ticks["max_us"], b["max_us"], lim_us,
                                        TICK_MS, ticks["over_20ms"],
                                        b["over_20ms"], lim_n))
    return ticks["max_us"] <= lim_us and ticks["over_20ms"] <= lim_n, msg


