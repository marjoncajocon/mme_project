def _chmod_retry(fn, path, exc):
    os.chmod(path, stat.S_IWRITE)
    fn(path)


def wipe(path):
    """Windows holds an exe for a moment after it exits: try again, briefly."""
    for i in range(20):
        if not os.path.exists(path):
            return
        try:
            if os.path.isdir(path):
                shutil.rmtree(path, onerror=_chmod_retry)
            else:
                os.chmod(path, stat.S_IWRITE)
                os.unlink(path)
            return
        except OSError:
            time.sleep(0.1)
    raise SystemExit("cannot clear %s" % path)


def prepare(scen, exe_src):
    """a private folder with its own mme.exe and its own empty mme-data"""
    d = os.path.join(WORK, scen.name)
    exe = os.path.join(d, "mme.exe")
    wipe(os.path.join(d, "mme-data"))
    wipe(os.path.join(d, "target"))
    os.makedirs(os.path.join(d, "mme-data"))
    src = os.stat(exe_src)
    if not os.path.isfile(exe) or os.stat(exe).st_size != src.st_size             or os.stat(exe).st_mtime < src.st_mtime:
        wipe(exe)
        shutil.copyfile(exe_src, exe)
    conf = dict(SEED_JSON)
    conf.update(scen.settings)
    stub = "python " + os.path.join(HERE, "stublsp.py").replace("\\", "/")
    if scen.stub_lsp:
        servers = dict(conf["mme.languageServers"])
        for lang in scen.stub_lsp:
            servers[lang] = stub
        conf["mme.languageServers"] = servers
    if scen.inline_lsp:
        conf["mme.inlineCompletionServer"] = stub + " --auth=" + scen.inline_lsp
    io.open(os.path.join(d, "mme-data", "settings.json"), "w", encoding="utf-8",
            newline="\n").write(json.dumps(conf, indent=2) + "\n")
    return d


def target_path(scen, work):
    src = scen.target if os.path.isabs(scen.target) else os.path.join(FIX, scen.target)
    if not scen.private:
        return src
    dst = os.path.join(work, "target", os.path.basename(src))
    if os.path.isdir(src):
        shutil.copytree(src, dst)
    else:
        os.makedirs(os.path.dirname(dst))
        shutil.copyfile(src, dst)
    return dst


def run_once(scen, use_prof):
    work = prepare(scen, PBIN if use_prof else BIN)
    tgt = target_path(scen, work)
    env = dict(os.environ)
    log = os.path.join(work, "tick.log")
    env["MME_TICKLOG"] = log
    # nothing below may reach into the user's own git or VS Code configuration
    env["GIT_CONFIG_GLOBAL"] = os.path.join(FIX, "gitconfig-none")
    env["GIT_CONFIG_SYSTEM"] = os.path.join(FIX, "gitconfig-none")
    # this suite is inside the editor's own checkout, and a fixture that is
    # not meant to be in a repository must not find that one by walking up
    env["GIT_CEILING_DIRECTORIES"] = BUILD
    if scen.fake_browser:
        # mme opens a URL with "rundll32 url.dll,FileProtocolHandler <url>", and
        # find_program takes the first rundll32 on the PATH: this one writes the
        # URL to MME_URLLOG and exits, so no browser window is ever opened
        env["PATH"] = BROWSER + os.pathsep + env.get("PATH", "")
        env["MME_URLLOG"] = os.path.join(work, "urls.txt")
    cmd = [HARNESS, os.path.join(work, "mme.exe"), tgt] + scen.steps
    t0 = time.time()
    try:
        r = subprocess.run(cmd, env=env, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, timeout=180)
        out = r.stdout
    except subprocess.TimeoutExpired:
        out = b"*** the harness did not finish in 180 s ***\n"
    took = time.time() - t0
    text = normalise(out.decode("utf-8", "replace"), scen.subs)
    text += watched(scen, work)
    ticks = read_ticks(log) if use_prof else None
    return text, ticks, took


def watched(scen, work):
    """What the run left of the files the scenario watches, as golden lines.
    A file mme must not touch shows its length and its first bytes; one that
    is gone says so."""
    out = ""
    for rel in scen.watch:
        p = os.path.join(work, "target", rel.replace("/", os.sep))
        if not os.path.isfile(p):
            out += "file %s: gone\n" % rel
            continue
        b = io.open(p, "rb").read()
        head = b[:40].decode("utf-8", "replace").replace("\n", "\\n").replace("\r", "\\r")
        out += "file %s: %d bytes, starts %s\n" % (rel, len(b), head)
    return out


BLANK_RX = re.compile(r"^(?:---- cursor [\d,]+|exited=\d+|\|\s*|[{\[<][0-9a-f-]*[}\]>]\s*)$")


def looks_blank(text):
    """True when mme drew nothing at all: it had not started yet, so the waits
    in the scenario were too short for how busy the machine was."""
    for line in text.splitlines():
        if not BLANK_RX.match(line):
            return False
    return True


# one draw of a 500 KB line is noisy: a cold cache or another process doubles
# it. A perf scenario is run a few times and the median is what counts.
PERF_REPS = 3


def median(v):
    v = sorted(v)
    return v[len(v) // 2]


def run_one(scen, use_prof, want=None):
    """want: the golden this run is compared against. A run that does not match
    it is tried once more before it is believed - see retry_note()."""
    if not use_prof:
        r = run_once(scen, False)
        if looks_blank(r[0]) or (want is not None and r[0] != want):
            r2 = run_once(scen, False)   # once more, with the machine less busy
            if looks_blank(r[0]):
                return r2 if not looks_blank(r2[0]) else r
            if r2[0] == want:
                FLAKY.append(scen.name)
                return r2
        return r
    runs = [run_once(scen, True) for _ in range(PERF_REPS)]
    text, _, _ = runs[0]
    ticks = {"max_us": median([r[1]["max_us"] for r in runs]),
             "over_20ms": median([r[1]["over_20ms"] for r in runs])}
    return text, ticks, sum(r[2] for r in runs)


FLAKY = []	# scenarios that failed once and passed on the retry


TICK_RX = re.compile(r"tick: total (\d+)")


def read_ticks(path):
    if not os.path.isfile(path):
        return {"max_us": 0, "over_20ms": 0}
    mx, n = 0, 0
    for line in io.open(path, encoding="utf-8", errors="replace"):
        m = TICK_RX.search(line)
        if m:
            n += 1
            mx = max(mx, int(m.group(1)))
    return {"max_us": mx, "over_20ms": n}


