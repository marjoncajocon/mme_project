def click(col, row):
    """an SGR mouse press and release at 1-based column/row"""
    return ["k:`[<0;%d;%dM" % (col, row), "k:`[<0;%d;%dm" % (col, row)]


def crows(*rows):
    """text-colour dumps of those screen rows (0 based: 0 menu, 29 status bar)"""
    return ["c:%d" % r for r in rows]


def brows(*rows):
    """background-colour dumps: the selection, the find matches, the diff"""
    return ["b:%d" % r for r in rows]


def arows(*rows):
    """attribute dumps: bold, italic, the curly underline of a diagnostic"""
    return ["a:%d" % r for r in rows]


