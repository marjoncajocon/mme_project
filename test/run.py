def stub_cmd(*args):
    """stublsp.py as a settings.json command, for a scenario that needs two of
    them with different arguments (stub_lsp= gives every language the same one)"""
    return " ".join(["python", os.path.join(HERE, "stublsp.py").replace("\\", "/")] +
                    list(args))


class Scen(object):
    """One scenario: what to open, what to press, and what it guards."""

    def __init__(self, name, target, steps, guards, settings=None, subs=None,
                 perf=False, private=False, stub_lsp=(), watch=(),
                 inline_lsp=None, fake_browser=False, stub_claude=None):
        self.stub_lsp = stub_lsp    # languages that get reg/stublsp.py
        self.inline_lsp = inline_lsp  # stublsp.py as mme.inlineCompletionServer,
                                    # with this --auth= state ("out", "in",
                                    # "error", "busy")
        self.fake_browser = fake_browser  # reg/browser goes in front of the PATH,
                                    # so opening a URL runs the no-op rundll32
                                    # there and never a real browser window
        self.stub_claude = stub_claude  # stubclaude.py as the Messages API, with
                                    # this --mode= ("ok", "401", "529",
                                    # "refusal"); mme.chat.baseUrl points at it
                                    # and mme.chat.apiKey is its dummy key
        self.name = name
        self.target = target        # relative to fix/, or an absolute path
        self.steps = steps          # harness steps
        self.guards = guards        # one line: what a failure here means
        self.settings = settings or {}   # settings.json values over the seed
        self.subs = subs or []      # extra (regex, replacement) masks
        self.perf = perf            # also assert on the event-loop tick profile
        self.private = private      # give the scenario its own copy of target
        self.watch = watch          # names under the scenario's own target folder
                                    # whose bytes are reported after the run; needs
                                    # private=True, or there is nothing mme may write to


# keys that go in as raw CSI u (the kitty protocol): "<code>;<mods>u",
# mods = 1 + 1*shift + 2*alt + 4*ctrl
def csiu(ch, ctrl=False, shift=False, alt=False):
    mods = 1 + (1 if shift else 0) + (2 if alt else 0) + (4 if ctrl else 0)
    return "`[%d;%du" % (ord(ch), mods)


